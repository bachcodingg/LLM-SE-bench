"""
Three refactorings of the same God Class, through the same check an agent gets.

Each one is sent to ``evaluate_patch`` — the tool the ``llm-se-bench`` MCP
server exposes — which runs the task's JUnit suite in Docker and then scores
the structure::

    python scripts/demo.py            # GC_001, the three versions below
    python scripts/demo.py --task GC_003 --file my_refactoring.java

1. **Unchanged.** Passes every test. Not credited: the class still holds all
   of its own logic.
2. **Empty shells.** The original with three empty classes added. Every CK
   metric "improves". Not credited: the new classes do nothing.
3. **A real decomposition**, generated by a model during the October 2026
   run. Passes and is credited.

The first two are the cheap imitations a pass/fail harness rewards. Makes
no API call and costs nothing.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

DEMO_DIR = REPO_ROOT / "docs" / "demo"

_SHELLS = """
class OrderValidator {
}

class InventoryStore {
}

class PaymentGateway {
}
"""


def versions(task_id: str, extra: Path | None) -> list[tuple[str, str]]:
    """(label, source) for each version to evaluate."""
    from bench.datasets.godclass import GodClassDataset

    original = GodClassDataset(data_dir=str(REPO_ROOT / "data")).get_original_code(task_id)
    found = [
        ("Unchanged: the original class, submitted as its own refactoring", original),
        ("Empty shells: the original plus three classes with no methods",
         original.rstrip() + "\n" + _SHELLS),
    ]
    reference = extra or DEMO_DIR / f"{task_id}_refactored.java"
    if reference.exists():
        found.append((f"Decomposition: {reference.name}", reference.read_text(encoding="utf-8")))
    return found


def show(label: str, result) -> None:
    """Print one evaluation the way the dashboard shows it."""
    credited = bool(result.structural.get("credited"))
    print(f"\n== {label}")
    if not result.ok:
        print(f"   error: {result.error}")
        return
    executed = "" if result.executed else "  (NOT executed: Docker unavailable)"
    print(f"   tests      {result.tests_passed}/{result.tests_total}{executed}")
    print(f"   structure  {'credited' if credited else 'not credited'}")
    print(f"   verdict    {result.verdict.upper()}")
    axes = result.structural.get("structure", {}).get("axes", {})
    if axes:
        print("   axes       " + "  ".join(f"{name.split('_')[0]} {value:+.2f}"
                                          for name, value in axes.items()))
    for reason in result.structural_reasons:
        print(f"   why        {reason}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("--task", default="GC_001")
    parser.add_argument("--file", type=Path, default=None,
                        help="A refactoring of your own to evaluate as the third version.")
    args = parser.parse_args(argv)

    from mcp_servers.tools.bench import evaluate_patch

    for label, source in versions(args.task, args.file):
        show(label, evaluate_patch(args.task, source, data_dir=str(REPO_ROOT / "data")))
    print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
